#!/usr/bin/env node
// Emits the per-icon Storybook stories into stories/generated/ (ignored by git), grouped by first
// character so the sidebar reads Icons/A, Icons/B, ..., Icons/0-9:
//   - icon-groups/<group>.ts      component classes of every package (style x fill) for each icon in the group
//   - icon-groups/index.ts        group keys and lazy loaders (the catalog imports groups on demand)
//   - icons-<group>.stories.ts    one story per icon, rendered by stories/icon-detail
// Reads the generated component maps, so run it after `pnpm icons:ensure`. Unchanged files are not
// rewritten, which keeps Storybook's dev server from reloading needlessly.
import fs from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';

const repoRoot = process.cwd();
const outDir = path.join(repoRoot, 'stories/generated');
const groupsDir = path.join(outDir, 'icon-groups');

const upstream = JSON.parse(
  await fs.readFile(path.join(repoRoot, 'tools/icons/upstream.json'), 'utf8'),
);
// Target id -> generated icons dir; ids match IconVariant in stories/icon-types.ts.
const VARIANTS = Object.fromEntries(
  Object.values(upstream.targets).map(({ id, projectPath }) => [
    id,
    `${projectPath}/src/lib/icons`,
  ]),
);

// Icon names that cannot be used as a bare `export const` binding.
const RESERVED = new Set(
  (
    'break case catch class const continue debugger default delete do else enum export extends ' +
    'false finally for function if import in instanceof new null return super switch this throw ' +
    'true try typeof var void while with let static yield await implements interface package ' +
    'private protected public arguments eval'
  ).split(' '),
);

async function readComponentMap(iconsDir) {
  const source = await fs.readFile(path.join(repoRoot, iconsDir, 'component-map.ts'), 'utf8');
  const modules = new Map();
  for (const [, className, specifier] of source.matchAll(
    /import \{ (\w+) \} from '(\.\/generated\/[^']+)';/g,
  )) {
    modules.set(className, path.posix.join(iconsDir, specifier));
  }
  const icons = new Map();
  for (const [, name, className] of source.matchAll(/^ {2}'([^']+)': (\w+),$/gm)) {
    const modulePath = modules.get(className);
    if (!modulePath)
      throw new Error(`No import found for ${className} in ${iconsDir}/component-map.ts`);
    icons.set(name, { className, modulePath });
  }
  if (icons.size === 0) throw new Error(`No icons found in ${iconsDir}/component-map.ts`);
  return icons;
}

const groupOf = (name) => (/^[0-9]/.test(name) ? '0-9' : name[0].toLowerCase());
const groupTitle = (group) => (group === '0-9' ? group : group.toUpperCase());
const exportNameOf = (name) => (/^[0-9]/.test(name) || RESERVED.has(name) ? `_${name}` : name);
const importFrom = (fromDir, modulePath) =>
  path.posix.relative(fromDir, modulePath).replace(/\.ts$/, '');

async function writeIfChanged(filePath, content) {
  const existing = await fs.readFile(filePath, 'utf8').catch(() => null);
  if (existing === content) return false;
  await fs.writeFile(filePath, content, 'utf8');
  return true;
}

const variants = {};
for (const [variant, iconsDir] of Object.entries(VARIANTS)) {
  variants[variant] = await readComponentMap(iconsDir);
}

const names = [...new Set(Object.values(variants).flatMap((icons) => [...icons.keys()]))].sort(
  (a, b) => a.localeCompare(b),
);
const groups = new Map();
for (const name of names) {
  const group = groupOf(name);
  if (!groups.has(group)) groups.set(group, []);
  groups.get(group).push(name);
}

await fs.mkdir(groupsDir, { recursive: true });
const header = '// Generated by tools/icons/emit-icon-stories.mjs. Do not edit.\n';
const expected = new Set();
let changed = 0;

for (const [group, groupNames] of groups) {
  const imports = [];
  const entries = [];
  for (const name of groupNames) {
    const parts = [];
    for (const variant of Object.keys(VARIANTS)) {
      const icon = variants[variant].get(name);
      if (!icon) continue;
      imports.push(
        `import { ${icon.className} } from '${importFrom('stories/generated/icon-groups', icon.modulePath)}';`,
      );
      parts.push(`'${variant}': { component: ${icon.className}, className: '${icon.className}' }`);
    }
    entries.push(`  '${name}': { ${parts.join(', ')} },`);
  }
  const groupFile = `${group}.ts`;
  expected.add(path.join(groupsDir, groupFile));
  changed += await writeIfChanged(
    path.join(groupsDir, groupFile),
    `${header}import type { IconGroup } from '../../icon-types';\n${imports.join('\n')}\n\n` +
      `export const ICONS: IconGroup = {\n${entries.join('\n')}\n};\n`,
  );

  const storiesFile = `icons-${group}.stories.ts`;
  expected.add(path.join(outDir, storiesFile));
  const stories = groupNames.map(
    (name) =>
      `export const ${exportNameOf(name)}: Story = { name: '${name}', args: { name: '${name}' } };`,
  );
  changed += await writeIfChanged(
    path.join(outDir, storiesFile),
    `${header}import type { Meta, StoryObj } from '@storybook/angular';\n` +
      `import { iconDetailMeta, type IconDetailArgs } from '../icon-detail';\n` +
      `import { ICONS } from './icon-groups/${group}';\n\n` +
      `const meta: Meta<IconDetailArgs> = {\n  title: 'Icons/${groupTitle(group)}',\n  ...iconDetailMeta(ICONS),\n};\n\n` +
      `export default meta;\ntype Story = StoryObj<IconDetailArgs>;\n\n${stories.join('\n')}\n`,
  );
}

const groupKeys = [...groups.keys()];
expected.add(path.join(groupsDir, 'index.ts'));
changed += await writeIfChanged(
  path.join(groupsDir, 'index.ts'),
  `${header}import type { IconGroup } from '../../icon-types';\n\n` +
    `export const ICON_GROUP_LOADERS: Record<string, () => Promise<IconGroup>> = {\n` +
    groupKeys
      .map((group) => `  '${group}': () => import('./${group}').then((m) => m.ICONS),`)
      .join('\n') +
    `\n};\n`,
);

for (const dir of [outDir, groupsDir]) {
  for (const entry of await fs.readdir(dir, { withFileTypes: true })) {
    const filePath = path.join(dir, entry.name);
    if (entry.isFile() && !expected.has(filePath)) await fs.rm(filePath);
  }
}

console.log(
  `Icon stories: ${names.length} icons in ${groupKeys.length} groups (${changed} files updated).`,
);
